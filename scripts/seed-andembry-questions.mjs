// Emit the data as JSON (no network) so it can be applied from a context that
// can reach Supabase (e.g. the browser): EMIT_JSON=1 node <this>
if (process.env.EMIT_JSON) {
  console.log(JSON.stringify(QUESTIONS));
  process.exit(0);
}

const { error: delErr } = await supabase
  .from("questions")
  .delete()
  .eq("quiz_id", QUIZ_ID);
if (delErr) {
  console.error("delete failed:", delErr);
  process.exit(1);
}
console.log("deleted old questions");

for (let i = 0; i < QUESTIONS.length; i++) {
  const item = QUESTIONS[i];
  const { data: q, error: qErr } = await supabase
    .from("questions")
    .insert({
      quiz_id: QUIZ_ID,
      question_text: item.q,
      type: "multiple_choice",
      position: i,
      time_limit: 30,
    })
    .select()
    .single();
  if (qErr) {
    console.error(`Q${i + 1} insert failed:`, qErr);
    process.exit(1);
  }
  const opts = item.opts.map((t, idx) => ({
    question_id: q.id,
    text: t,
    is_correct: idx === item.correct,
    position: idx,
  }));
  const { error: oErr } = await supabase.from("answer_options").insert(opts);
  if (oErr) {
    console.error(`Q${i + 1} options insert failed:`, oErr);
    process.exit(1);
  }
  console.log(`Q${i + 1}: ${item.opts.length} opts, correct=#${item.correct}`);
}
console.log("✅ seeded 20 questions");
